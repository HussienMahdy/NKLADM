-- بوابة بيانات إدارة نخل التعليمية
-- نفّذ هذا الملف في Supabase Dashboard > SQL Editor
create table if not exists public.staff_records (
  id bigint generated by default as identity primary key,
  sheet_name text not null check (sheet_name in ('ادارة نخل بالمدارس','المنتدبين','الاجازات الخاصة','محاكمة تأديبية')),
  row_number integer not null,
  data jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now()
);
create index if not exists staff_records_sheet_name_idx on public.staff_records(sheet_name);
create index if not exists staff_records_data_gin_idx on public.staff_records using gin(data);
alter table public.staff_records enable row level security;
-- جميع المستخدمين المسجلين والمضافين يدويًا في Auth لديهم نفس صلاحية البحث/الاستيراد.
drop policy if exists "authenticated can read records" on public.staff_records;
create policy "authenticated can read records" on public.staff_records for select to authenticated using (true);
drop policy if exists "authenticated can insert records" on public.staff_records;
create policy "authenticated can insert records" on public.staff_records for insert to authenticated with check (true);
drop policy if exists "authenticated can delete records" on public.staff_records;
create policy "authenticated can delete records" on public.staff_records for delete to authenticated using (true);
grant select, insert, delete on public.staff_records to authenticated;
grant usage, select on sequence public.staff_records_id_seq to authenticated;
